import SwiftUI

/// Design system spacing values used across the app.
/// Use these instead of hardcoded numbers for consistency.
enum Space {
    
    static let zero: CGFloat = 0
    
    /// 2pt – Extra extra small spacing
    static let xxs: CGFloat = 2
    
    /// 4pt – Extra small spacing
    static let xs: CGFloat = 4

    /// 8pt – Small spacing
    static let sm: CGFloat = 8

    /// 12pt – Medium spacing
    static let md: CGFloat = 12

    /// 16pt – Large spacing (base spacing)
    static let lg: CGFloat = 16

    /// 20pt – Extra large spacing
    static let xl: CGFloat = 20

    /// 24pt – Double extra large spacing
    static let xxl: CGFloat = 24

    /// 32pt – Triple extra large spacing
    static let xxxl: CGFloat = 32

    /// 40pt – Huge spacing
    static let huge: CGFloat = 40
}
